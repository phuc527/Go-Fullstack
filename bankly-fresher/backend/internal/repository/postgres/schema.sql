-- Chạy mỗi lần backend khởi động. Mọi lệnh đều "IF NOT EXISTS" / "OR REPLACE" nên chạy lại không sao.
-- ponytail: 1 file schema cho gọn; khi cần sửa bảng đã có dữ liệu thì chuyển sang migration (goose/migrate).

CREATE TABLE IF NOT EXISTS accounts (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner      TEXT        NOT NULL,
  currency   TEXT        NOT NULL DEFAULT 'VND' CHECK (currency = 'VND'),
  status     TEXT        NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'FROZEN')),
  balance    BIGINT      NOT NULL DEFAULT 0, -- tiền: BIGINT (đồng), không bao giờ FLOAT
  is_system  BOOLEAN     NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- Lưới an toàn cuối cùng: dù code có bug, DB cũng không cho tài khoản khách bị âm.
  CHECK (is_system OR balance >= 0)
);

CREATE TABLE IF NOT EXISTS transactions (
  id                  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  idempotency_key     TEXT        NOT NULL UNIQUE, -- request lặp lại cùng key → không ghi sổ lần 2
  request_fingerprint TEXT        NOT NULL,
  kind                TEXT        NOT NULL CHECK (kind IN ('DEPOSIT', 'TRANSFER', 'REVERSAL')),
  amount              BIGINT      NOT NULL CHECK (amount > 0),
  reverses_id         BIGINT      UNIQUE REFERENCES transactions (id), -- UNIQUE: chỉ đảo ngược 1 lần
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS ledger_entries (
  id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  transaction_id BIGINT      NOT NULL REFERENCES transactions (id),
  account_id     BIGINT      NOT NULL REFERENCES accounts (id),
  direction      TEXT        NOT NULL CHECK (direction IN ('DEBIT', 'CREDIT')),
  amount         BIGINT      NOT NULL CHECK (amount > 0),
  balance_after  BIGINT      NOT NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ledger_entries_account_idx ON ledger_entries (account_id, id DESC);
CREATE INDEX IF NOT EXISTS ledger_entries_transaction_idx ON ledger_entries (transaction_id);

-- Transactional Outbox: ghi CÙNG transaction với bút toán. Tiến trình khác đọc bảng này
-- rồi đẩy sang Kafka/gửi thông báo. Chưa có tiến trình đó (xem README, Các level).
CREATE TABLE IF NOT EXISTS outbox_events (
  id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  topic        TEXT        NOT NULL,
  payload      JSONB       NOT NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  published_at TIMESTAMPTZ
);

-- Bất biến (immutable): DB từ chối mọi UPDATE/DELETE/TRUNCATE lên sổ cái và lịch sử giao dịch.
-- Sai thì sửa bằng bút toán đảo ngược (REVERSAL), không sửa dòng cũ.
CREATE OR REPLACE FUNCTION forbid_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '% is append-only: % is not allowed, post a reversal instead', TG_TABLE_NAME, TG_OP;
END $$;

CREATE OR REPLACE TRIGGER ledger_entries_no_change BEFORE UPDATE OR DELETE ON ledger_entries
  FOR EACH ROW EXECUTE FUNCTION forbid_change();
CREATE OR REPLACE TRIGGER ledger_entries_no_truncate BEFORE TRUNCATE ON ledger_entries
  FOR EACH STATEMENT EXECUTE FUNCTION forbid_change();
CREATE OR REPLACE TRIGGER transactions_no_change BEFORE UPDATE OR DELETE ON transactions
  FOR EACH ROW EXECUTE FUNCTION forbid_change();
CREATE OR REPLACE TRIGGER transactions_no_truncate BEFORE TRUNCATE ON transactions
  FOR EACH STATEMENT EXECUTE FUNCTION forbid_change();

-- Quỹ tiền mặt của ngân hàng là tài khoản đầu tiên (id = 1, khớp domain.SystemAccountID).
INSERT INTO accounts (owner, is_system)
SELECT 'Quỹ tiền mặt ngân hàng', true
WHERE NOT EXISTS (SELECT 1 FROM accounts);
